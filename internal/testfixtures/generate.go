// Music.

func (g *generator) music(ctx context.Context) error {
	album := filepath.Join(g.root, "Music", "Artist Test", "Album Test (2020)")
	cover := filepath.Join(album, "folder.jpg")
	if err := g.image(ctx, cover, "color=c=0x3a5f1e:s=600x600"); err != nil {
		return err
	}
	tracks := []struct {
		file, title, codec string
		n, freq            int
	}{
		{"01 - Track One.flac", "Track One", "flac", 1, 262},
		{"02 - Track Two.mp3", "Track Two", "libmp3lame", 2, 294},
	}
	for _, tr := range tracks {
		path := filepath.Join(album, tr.file)
		if g.exists(path) {
			continue
		}
		args := []string{
			"-f", "lavfi", "-i", fmt.Sprintf("sine=frequency=%d:sample_rate=44100:duration=%s", tr.freq, duration),
			"-i", cover, "-map", "0:a", "-map", "1:v",
			"-c:a", tr.codec, "-c:v", "mjpeg", "-disposition:v", "attached_pic",
			"-metadata", "title=" + tr.title, "-metadata", "artist=Artist Test",
			"-metadata", "album_artist=Artist Test", "-metadata", "album=Album Test",
			"-metadata", "date=2020", "-metadata", "genre=Electro", "-metadata", fmt.Sprintf("track=%d/2", tr.n),
		}
		if tr.codec == "libmp3lame" {
			args = append(args, "-id3v2_version", "3")
		}
		if err := g.ffmpegTo(ctx, path, args...); err != nil {
			return err
		}
	}
	return g.moreMusic(ctx)
}

