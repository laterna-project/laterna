// Version identifies the generated content. Bump it whenever the generator changes so that existing
// copies are regenerated.
const Version = "8"

// renamed is the version that gave every fixture a new name. A library generated before it is
// emptied first: none of its files would be replaced, and the tests would find both sets. Only a
// folder that carries the marker of an older generation is emptied, never one the generator did
// not write.
const renamed = 8

// Options configures the generation.
type Options struct {
	FFmpeg string
	Force  bool
	// Log receives one line per file created; nil means silent.
	Log func(string)
}

// changed lists, per version, the fixtures whose content changed: a library generated by an older
// version loses them before being completed (files that are present are otherwise kept as they
// are).
var changed = map[int][]string{}

// Generate writes the library into root. Files already there are kept (unless Force), except those
// changed by a version newer than the library's.
func Generate(ctx context.Context, root string, opts Options) (made, skipped int, err error) {
	if opts.FFmpeg == "" {
		opts.FFmpeg = "ffmpeg"
	}
	unlock, err := lockLibrary(root)
	if err != nil {
		return 0, 0, err
	}
	defer unlock()
	old := 0
	if v, err := os.ReadFile(filepath.Join(root, markerFile)); err == nil {
		old, _ = strconv.Atoi(strings.TrimSpace(string(v)))
	}
	if old > 0 && old < renamed {
		if err := empty(root); err != nil {
			return 0, 0, err
		}
	}
	for v, paths := range changed {
		if v <= old {
			continue
		}
		for _, p := range paths {
			if err := os.RemoveAll(filepath.Join(root, filepath.FromSlash(p))); err != nil {
				return 0, 0, err
			}
		}
	}
	g := &generator{root: root, ffmpeg: opts.FFmpeg, force: opts.Force, log: opts.Log}
	if err := g.run(ctx); err != nil {
		return g.made, g.skipped, err
	}
	return g.made, g.skipped, os.WriteFile(filepath.Join(root, markerFile), []byte(Version), 0o600)
}

// empty removes everything from the library except the lock file, which this process holds.
func empty(root string) error {
	entries, err := os.ReadDir(root)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.Name() == lockName {
			continue
		}
		if err := os.RemoveAll(filepath.Join(root, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

// markerFile marks a complete generation, and its version.
const markerFile = ".fixtures-version"

// lockName is the file that reserves the library for one process at a time.
const lockName = ".generate.lock"

// lockLibrary reserves the library for this process until the returned function is called. Test
// packages run in parallel processes: without a lock, one deletes the fixtures of a stale version
// while another is writing them (marker not written yet).
func lockLibrary(root string) (unlock func(), err error) {
	if err := os.MkdirAll(root, 0o750); err != nil {
		return nil, err
	}
	f, err := os.OpenFile(filepath.Join(root, lockName), os.O_CREATE|os.O_RDWR, 0o600)
	if err != nil {
		return nil, err
	}
	if err := lockFile(f); err != nil {
		_ = f.Close()
		return nil, fmt.Errorf("locking the fixtures: %w", err)
	}
	return func() { _ = f.Close() }, nil
}

type generator struct {
	root    string
	ffmpeg  string
	force   bool
	log     func(string)
	made    int
	skipped int
	tmp     string
}

// Length of each video: enough for three chapters and several 4 s HLS segments.
const duration = "12"

func (g *generator) run(ctx context.Context) error {
	tmp, err := os.MkdirTemp("", "testfixtures-")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(tmp) }()
	g.tmp = tmp

	steps := []func(context.Context) error{g.movies, g.series, g.anime, g.music, g.subtitled, g.books, g.photos}
	for _, step := range steps {
		if err := step(ctx); err != nil {
			return err
		}
	}
	return nil
}

// Movies.

func (g *generator) movies(ctx context.Context) error {
	movies := filepath.Join(g.root, "Movies")

	// MP4 with H.264 and AAC: the simplest case, plays directly everywhere.
	dir := filepath.Join(movies, "Big Test Movie (2020)")
	if err := g.video(ctx, filepath.Join(dir, "Big Test Movie (2020).mp4"), videoSpec{
		source: "testsrc2=s=640x360:r=24", audio: []audioSpec{{freq: 440, lang: "eng"}},
	}); err != nil {
		return err
	}
	if err := g.movieExtras(ctx, dir, "Big Test Movie", 2020, "A test movie, as a plain MP4.", "Adventure"); err != nil {
		return err
	}

	// Multi-track MKV: two audio streams (French by default, Japanese), ASS and SRT subtitles,
	// chapters.
	dir = filepath.Join(movies, "Dual Audio (2019)")
	if err := g.video(ctx, filepath.Join(dir, "Dual Audio (2019).mkv"), videoSpec{
		source: "smptehdbars=s=640x360:r=24",
		audio:  []audioSpec{{freq: 330, lang: "fre", title: "French", isDefault: true}, {freq: 550, lang: "jpn", title: "日本語"}},
		subs:   []subSpec{{kind: "ass", lang: "fre", title: "French (ASS)"}, {kind: "srt", lang: "eng", title: "English"}},
		chapters: []chapter{
			{0, 3000, "OP"}, {3000, 9000, "Episode"}, {9000, 12000, "ED"},
		},
	}); err != nil {
		return err
	}
	if err := g.movieExtras(ctx, dir, "Dual Audio", 2019, "Two audio tracks, ASS and SRT subtitles, chapters.", "Animation"); err != nil {
		return err
	}

	// 10-bit HDR10 HEVC with 5.1 audio: forces transcoding in a browser.
	dir = filepath.Join(movies, "HDR Test (2021)")
	if err := g.video(ctx, filepath.Join(dir, "HDR Test (2021).mkv"), videoSpec{
		source: "testsrc2=s=640x360:r=24", hevcHDR: true,
		audio: []audioSpec{{freq: 220, lang: "eng", channels: 6}},
	}); err != nil {
		return err
	}
	if err := g.movieExtras(ctx, dir, "HDR Test", 2021, "10-bit HEVC in HDR10, 5.1 audio.", "Science Fiction"); err != nil {
		return err
	}

	// MKV without an index (Cues): a case where a player cannot seek in the file.
	dir = filepath.Join(movies, "Stream Dump (2018)")
	if err := g.video(ctx, filepath.Join(dir, "Stream Dump (2018).mkv"), videoSpec{
		source: "testsrc=s=640x360:r=24", audio: []audioSpec{{freq: 660, lang: "fre"}}, noCues: true,
	}); err != nil {
		return err
	}
	if err := g.movieExtras(ctx, dir, "Stream Dump", 2018, "Matroska written without an index (Cues).", "Drama"); err != nil {
		return err
	}

	// Two versions of the same movie in one folder.
	dir = filepath.Join(movies, "Versions (2017)")
	for _, v := range []struct{ name, size string }{{"1080p", "640x360"}, {"720p", "320x180"}} {
		if err := g.video(ctx, filepath.Join(dir, "Versions (2017) - "+v.name+".mp4"), videoSpec{
			source: "testsrc2=s=" + v.size + ":r=24", audio: []audioSpec{{freq: 440, lang: "fre"}},
		}); err != nil {
			return err
		}
	}
	return g.movieExtras(ctx, dir, "Versions", 2017, "A movie in two versions.", "Comedy")
}

func (g *generator) movieExtras(ctx context.Context, dir, title string, year int, plot, genre string) error {
	nfo := fmt.Sprintf(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<movie>
  <title>%s</title>
  <year>%d</year>
  <plot>%s</plot>
  <genre>%s</genre>
  <runtime>1</runtime>
</movie>
`, title, year, plot, genre)
	if err := g.text(filepath.Join(dir, "movie.nfo"), nfo); err != nil {
		return err
	}
	if err := g.image(ctx, filepath.Join(dir, "poster.jpg"), "color=c=0x1e3a5f:s=400x600"); err != nil {
		return err
	}
	return g.image(ctx, filepath.Join(dir, "fanart.jpg"), "testsrc2=s=1280x720")
}

